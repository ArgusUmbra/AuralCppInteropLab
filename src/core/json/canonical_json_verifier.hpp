#ifndef AURAL_CORE_JSON_CANONICAL_JSON_VERIFIER_HPP
#define AURAL_CORE_JSON_CANONICAL_JSON_VERIFIER_HPP

#include "canonical_json_document.hpp"
#include "json_value_parser.hpp"

#include <cstddef>
#include <cstdint>
#include <optional>
#include <span>
#include <string_view>

namespace aural::core::json {

// Internal experimental API. This verdict says only whether one bounded JSON
// byte sequence is already in canonical form. It does not establish manifest
// semantics, evidence authenticity, signature validity, or package validity.
enum class JsonCanonicalityStatus : std::uint8_t {
    canonical,
    invalid_document,
    noncanonical,
    resource_failure,
};

enum class JsonCanonicalityResource : std::uint8_t {
    input_limit_exceeded,
    nesting_limit_exceeded,
    value_limit_exceeded,
    decoded_string_limit_exceeded,
    canonical_output_limit_exceeded,
    allocation_failure,
    internal_serialization_failure,
};

struct JsonCanonicalityResult final {
    JsonCanonicalityStatus status;
    // Present only for noncanonical input. If one byte sequence is a prefix of
    // the other, this is the common length and therefore the first absent or
    // extra byte position.
    std::optional<std::size_t> mismatch_offset;
    std::optional<JsonValueError> parse_error;
    std::optional<CanonicalDocumentError> serialization_error;
    std::optional<JsonCanonicalityResource> resource;

    [[nodiscard]] bool canonical() const noexcept
    {
        return status == JsonCanonicalityStatus::canonical;
    }
};

// Parses the complete caller-owned document under the frozen AURAL limits,
// serializes the owned parse tree canonically under the distinct temporary
// output ceiling, and compares length and bytes. The source span is borrowed,
// never modified, and no regenerated bytes are returned.
[[nodiscard]] JsonCanonicalityResult verify_canonical_json(
    std::span<const std::byte> input) noexcept;

[[nodiscard]] std::string_view json_canonicality_status_message(
    JsonCanonicalityStatus status) noexcept;

[[nodiscard]] std::string_view json_canonicality_resource_message(
    JsonCanonicalityResource resource) noexcept;

} // namespace aural::core::json

#endif
